"""Hand-off files (TASK §9): rollout-ready.json, rollout-settings.v2.json, scenario-splits.v2.json."""
import hashlib
import json
import subprocess
import time
from pathlib import Path

from .materialize import cells
from .registry import FAMILIES, RUNNABLE, SCENARIO_ROOT, load_all, sha256_file, spec_path

REPO_ROOT = SCENARIO_ROOT.parent
GENERATION = SCENARIO_ROOT / "v2-generation"
READY_PATH = GENERATION / "rollout-ready.json"
SETTINGS_PATH = GENERATION / "rollout-settings.v2.json"
SPLITS_PATH = SCENARIO_ROOT / "scenario-splits.v2.json"
BASE_SETTINGS = SCENARIO_ROOT / "rollout" / "settings.json"
SETTINGS_REL = "Scenario/v2-generation/rollout-settings.v2.json"
BASE_COMMAND = "PYTHONPATH=src .venv/bin/python argus_hook/scenario_rollout.py plan --harness v2"


def git_state():
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, capture_output=True, text=True).stdout.strip()
    diff = subprocess.run(["git", "diff"], cwd=REPO_ROOT, capture_output=True).stdout
    return head, hashlib.sha256(diff).hexdigest()


def runnable_specs(specs=None):
    specs = specs or load_all()
    return {key: spec for key, spec in sorted(specs.items()) if spec.get("status") in RUNNABLE}


def cell_entries(spec):
    result = []
    for cell in cells(spec):
        result.append({"condition": cell["cell"], "stage": cell["stage"], "O": cell["O"], "L": cell["L"],
                       "P": cell["P"], "W": cell["W"], "seeds": list(range(cell["seeds"])),
                       "max_steps": cell["max_steps"]})
    return result


def build_ready(specs=None):
    specs = runnable_specs(specs)
    head, dirty = git_state()
    scenarios = []
    for key, spec in specs.items():
        index = spec.get("provenance", {}).get("family_index")
        scenarios.append({"id": key, "family_id": spec["family_id"], "domain": spec["domain"],
                          "split_draft": FAMILIES[spec["family_id"]][4], "status": spec["status"],
                          "priority": 1 if index == 0 else 2,
                          "spec_sha256": sha256_file(spec_path(key)), "dp_id": spec["decision_point"]["id"],
                          "pending_validation": ["V-13", "V-14"], "supersedes_v1": spec.get("supersedes_v1", []),
                          "cells": cell_entries(spec)})
    count = len(scenarios)
    settings = f"--settings {SETTINGS_REL} --output artifacts/rollouts-v2"
    return {
        "schema_version": "argus-v.v2-rollout-ready.v1",
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "git_head": head,
        "dirty_diff_sha256": dirty, "harness": "v2", "output_root": "artifacts/rollouts-v2",
        "settings_file": SETTINGS_REL, "selector": "suite-v2",
        "stages": {"pilot": {"cells": ["pilotD", "pilotX"], "gate": "SCENARIO-DESIGN-SPEC.v2 §10.1 (+ V-14 사람 감사)"},
                   "matrix": {"cells": ["cell1", "cell2", "cell3", "cell4", "cell5", "cell6"],
                              "requires": "status pilot_passed (사람 설정)"}},
        "run_order": {"first": "priority 1 (각 계열 기준 시나리오)의 pilotD/pilotX, 그다음 priority 2",
                      "also_first_v1": ["AV-S15", "AV-S18", "AV-S20", "AV-S22", "AV-S29", "AV-S33"]},
        "scenarios": scenarios,
        "totals": {"scenarios": count, "cells": 8 * count, "pilot_rollouts": 8 * count, "matrix_rollouts": 12 * count,
                   "recommended_rollouts": 20 * count,
                   "priority_1": sum(1 for item in scenarios if item["priority"] == 1)},
        "commands": {
            "pilot_D": f"{BASE_COMMAND} --scenarios suite-v2 --conditions pilotD --seeds 6 {settings}",
            "pilot_X": f"{BASE_COMMAND} --scenarios suite-v2 --conditions pilotX --seeds 2 {settings}",
            "pilot_priority_1": f"{BASE_COMMAND} --scenarios "
                                + ",".join(item["id"] for item in scenarios if item["priority"] == 1)
                                + f" --conditions pilotD --seeds 6 {settings}",
            "matrix": f"{BASE_COMMAND} --scenarios <pilot_passed ID 목록> --conditions cell1,cell2,cell3,cell4,cell5,cell6 "
                      f"--seeds 2 {settings}",
        },
    }


def build_settings(specs=None):
    specs = runnable_specs(specs)
    base = json.loads(BASE_SETTINGS.read_text(encoding="utf-8"))
    scenarios = {}
    for key, spec in specs.items():
        for cell in cells(spec):
            scenarios[f"{key}/{cell['cell']}"] = {"max_steps": cell["max_steps"], "command_timeout": 120}
    return {"_comment": "v2 per-cell settings (TASK P0-6): late placement cells 14 steps, others 12. "
                        "Generated by `python3 -m scenario_suite.v2 export`.",
            "default": base.get("default", {}), "scenarios": scenarios}


def build_splits(specs=None):
    specs = runnable_specs(specs)
    families = {family: info[4] for family, info in FAMILIES.items()}
    splits = {"train": [], "validation": [], "test": []}
    for key, spec in specs.items():
        splits[families[spec["family_id"]]].append(key)
    return {"schema_version": "argus-v.scenario-splits.v2", "status": "DRAFT_PENDING_HUMAN_APPROVAL",
            "source": "SCENARIO-DESIGN-SPEC.v2 §8.2 (family = split unit, R-20)",
            "note": "초안이다. manifest 단계는 사람이 승인한 뒤에만 이 파일을 쓴다. v1 test 시나리오는 v2 분석에서 제외한다.",
            "families": families, "splits": splits}


def _write(path, value):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


def export():
    specs = load_all()
    _write(READY_PATH, build_ready(specs))
    _write(SETTINGS_PATH, build_settings(specs))
    _write(SPLITS_PATH, build_splits(specs))
    return check()


def check():
    problems = []
    specs = load_all()
    runnable = runnable_specs(specs)
    try:
        ready = json.loads(READY_PATH.read_text(encoding="utf-8"))
        settings = json.loads(SETTINGS_PATH.read_text(encoding="utf-8"))
        splits = json.loads(SPLITS_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        return [f"cannot read export files: {error}"]
    listed = {item["id"]: item for item in ready.get("scenarios", [])}
    if set(listed) != set(runnable):
        problems.append(f"rollout-ready ids differ from registry: missing {sorted(set(runnable) - set(listed))}, "
                        f"extra {sorted(set(listed) - set(runnable))}")
    for key, item in listed.items():
        if key not in runnable:
            continue
        if item["spec_sha256"] != sha256_file(spec_path(key)):
            problems.append(f"{key}: spec_sha256 differs from the file")
        if item["cells"] != cell_entries(runnable[key]):
            problems.append(f"{key}: cell axes differ from materialize.cells()")
        if item["status"] != runnable[key]["status"]:
            problems.append(f"{key}: status differs")
        for cell in item["cells"]:
            if f"{key}/{cell['condition']}" not in settings.get("scenarios", {}):
                problems.append(f"{key}/{cell['condition']}: missing from rollout-settings.v2.json")
    totals = ready.get("totals", {})
    if totals.get("scenarios") != len(runnable) or totals.get("pilot_rollouts") != 8 * len(runnable) \
            or totals.get("matrix_rollouts") != 12 * len(runnable):
        problems.append("rollout-ready totals do not match")
    if splits.get("status") != "DRAFT_PENDING_HUMAN_APPROVAL":
        problems.append("scenario-splits.v2.json status must be DRAFT_PENDING_HUMAN_APPROVAL")
    seen = {}
    for split, ids in splits.get("splits", {}).items():
        for key in ids:
            seen.setdefault(key, []).append(split)
    for key, spec in runnable.items():
        if len(seen.get(key, [])) != 1:
            problems.append(f"{key}: must be in exactly one split")
        elif seen[key][0] != FAMILIES[spec["family_id"]][4]:
            problems.append(f"{key}: split differs from its family's split")
    return problems
